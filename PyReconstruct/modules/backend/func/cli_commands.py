"""Terminal commands for an installed PyReconstruct (Qt-free).

The stable app answers to ``pyrecon`` and ``pyreconstruct``, PyReconstruct Dev
to ``pyrecon-dev`` and ``pyreconstruct-dev``. The commands themselves ship in
the build (packaging/make_cli_shims.py) or come from the Linux installer. This
module is the part that runs at launch and makes sure they are reachable:

* macOS: links in ``/usr/local/bin`` to the scripts inside the bundle. Made
  only for a frozen app in /Applications or ~/Applications. A missing link,
  or one of ours whose target is gone (the app moved), is made with one
  administrator prompt after the user agrees. A file that is not one of our
  links is never touched. A declined or failed prompt is remembered and not
  asked again; a user who cannot authorize as an administrator is not asked.
* Windows: the install's ``bin`` folder on the per-user PATH. The installer
  adds it; this covers an install that an in-place update brought up to a
  build with commands. Once per app, no administrator rights.
* Linux: the short name beside the launcher install-appimage.sh wrote, for
  an AppImage install made before the installer wrote it. Once per app.

The decisions are pure functions over paths and strings; the side effects
(osascript, the registry, the settings store) are passed in, so tests drive
all of it against a temporary folder.
"""

import os
import shlex
import subprocess
import sys
from pathlib import Path

from PyReconstruct.modules.constants.settings_domain import SHARED_APP, settings_app

# Per-app settings keys (constants/settings_domain.PER_APP_KEYS).
DECLINED_KEY = "cli_commands_declined"  # macOS: the user said no, or the prompt failed
ADDED_KEY = "cli_commands_added"  # Windows and Linux: the one-time add ran

MACOS_LINK_DIR = Path("/usr/local/bin")
APPIMAGE_MARKER = ".appimage-install"  # install-appimage.sh's MARKER
LAUNCHER_TAG = "generated by install-appimage.sh"  # install-appimage.sh's LAUNCHER_TAG


def is_dev_flavor():
    return settings_app() != SHARED_APP


def command_names(dev=None):
    """(short, long) command names for this flavor, or for ``dev`` when given."""
    if dev is None:
        dev = is_dev_flavor()
    return ("pyrecon-dev", "pyreconstruct-dev") if dev else ("pyrecon", "pyreconstruct")


def _truthy(value):
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in ("1", "true", "yes")


def _flag(settings, key):
    try:
        return _truthy(settings.value(key, False))
    except Exception:
        return False


def _set_flag(settings, key):
    settings.setValue(key, True)
    try:
        settings.sync()
    except AttributeError:
        pass


# ------------------------------------------------------------------ launch path

def launch_file(argv, cwd=None):
    """The series path a launch was given, made absolute, or None.

    Arguments that start with ``-`` are not files (macOS may add
    ``-psn_...``); the first other argument is the file.
    """
    for arg in argv:
        if arg and not arg.startswith("-"):
            return os.path.abspath(os.path.join(cwd or os.getcwd(), arg))
    return None


# ---------------------------------------------------------------------- macOS

def macos_bundle_is_installed(bundle, home=None):
    """Whether ``bundle`` sits in /Applications or ~/Applications.

    Not on a disk image (/Volumes) and not an App Translocation copy, which
    macOS runs from a random read-only path that is gone after a restart.
    """
    path = os.path.normpath(str(bundle))
    if "/AppTranslocation/" in path or not path.endswith(".app"):
        return False
    home = os.path.normpath(str(home if home is not None else Path.home()))
    for root in ("/Applications", os.path.join(home, "Applications")):
        if path.startswith(root + os.sep):
            return True
    return False


def _is_our_kind_of_target(target, name):
    """A target inside some ``.app`` at Contents/Resources/bin/<name>."""
    tail = os.path.join("Contents", "Resources", "bin", name)
    if not target.endswith(os.sep + tail):
        return False
    return target[: -len(tail) - 1].endswith(".app")


def macos_link_states(bundle, link_dir=MACOS_LINK_DIR, names=None):
    """{name: (state, link path, wanted target, link text or None)}.

    The link text is what the link holds now (``readlink``). state is one of:
      ``ok``       the link points at this bundle's script
      ``missing``  nothing has the name
      ``moved``    one of our links whose target is gone (the app moved)
      ``other``    one of our links to another copy that still exists
      ``foreign``  a file, folder or link that is not ours
    """
    names = names or command_names()
    states = {}
    for name in names:
        link = os.path.join(str(link_dir), name)
        want = os.path.join(str(bundle), "Contents", "Resources", "bin", name)
        if not os.path.lexists(link):
            states[name] = ("missing", link, want, None)
            continue
        if not os.path.islink(link):
            states[name] = ("foreign", link, want, None)
            continue
        try:
            raw = os.readlink(link)
        except OSError:
            states[name] = ("foreign", link, want, None)
            continue
        target = os.path.normpath(os.path.join(os.path.dirname(link), raw))
        if target == os.path.normpath(want) or (
            os.path.exists(target) and os.path.realpath(target) == os.path.realpath(want)
        ):
            state = "ok"
        elif not _is_our_kind_of_target(target, name):
            state = "foreign"
        elif os.path.lexists(target):
            state = "other"
        else:
            state = "moved"
        states[name] = (state, link, want, raw)
    return states


def macos_fixes(states):
    """The (link, wanted target, link text or None) to write."""
    return [
        (link, want, current)
        for state, link, want, current in states.values()
        if state in ("missing", "moved")
    ]


def macos_fix_script(fixes, link_dir=MACOS_LINK_DIR):
    """A sh script that makes the links, refusing any name that changed since
    it was checked: a name that was free must still be free, and a moved
    link must still point where it did."""
    lines = ["set -e", f"mkdir -p {shlex.quote(str(link_dir))}"]
    for link, want, current in fixes:
        q = shlex.quote(link)
        if current is None:
            lines.append(f"if [ -e {q} ] || [ -L {q} ]; then exit 3; fi")
        else:
            lines.append(f'if [ ! -L {q} ] || [ "$(readlink {q})" != {shlex.quote(current)} ]; then exit 3; fi')
            lines.append(f"rm -f {q}")
        lines.append(f"ln -s {shlex.quote(want)} {q}")
    return "\n".join(lines)


def _applescript_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def osascript_argv(script, prompt):
    """argv for running ``script`` as an administrator through one prompt."""
    return [
        "osascript", "-e",
        f"do shell script {_applescript_string(script)} with administrator privileges "
        f"with prompt {_applescript_string(prompt)}",
    ]


def _is_macos_admin():
    try:
        import grp
        import pwd
        admin = grp.getgrnam("admin").gr_gid
        user = pwd.getpwuid(os.getuid()).pw_name
        return admin in os.getgrouplist(user, os.getgid())
    except Exception:
        return False


def macos_offer(bundle, settings, link_dir=MACOS_LINK_DIR, is_admin=_is_macos_admin,
                home=None, names=None):
    """The links to make, or None when there is nothing to ask the user.

    None for a bundle outside /Applications and ~/Applications, when every
    name is already ours or belongs to someone else, after a decline, and for
    a user who cannot authorize as an administrator.
    """
    if not macos_bundle_is_installed(bundle, home=home):
        return None
    if _flag(settings, DECLINED_KEY):
        return None
    fixes = macos_fixes(macos_link_states(bundle, link_dir, names))
    if not fixes or not is_admin():
        return None
    return fixes


def run_as_admin(script, prompt):
    """Run sh ``script`` as root through one macOS administrator prompt.
    True when it ran and exited 0; a canceled prompt is False."""
    done = subprocess.run(osascript_argv(script, prompt), capture_output=True, text=True, timeout=600)
    if done.returncode != 0:
        log_problem(f"terminal commands: osascript exited {done.returncode}: {done.stderr.strip()}")
    return done.returncode == 0


def macos_apply(fixes, settings, link_dir=MACOS_LINK_DIR, runner=run_as_admin):
    """Make the links through one administrator prompt. True on success.

    A canceled prompt, a wrong password or any other failure records the
    decline, so PyReconstruct does not ask again.
    """
    short, long_ = command_names()
    prompt = f"PyReconstruct wants to add the {short} and {long_} commands to {link_dir}."
    try:
        ok = bool(runner(macos_fix_script(fixes, link_dir), prompt))
    except Exception as e:
        log_problem(f"terminal commands: {e!r}")
        ok = False
    if not ok:
        macos_decline(settings)
    return ok


def macos_decline(settings):
    _set_flag(settings, DECLINED_KEY)


def own_macos_bundle(executable=None):
    from PyReconstruct.modules.backend.func.installer_image import own_bundle
    return own_bundle(executable)


# -------------------------------------------------------------------- Windows

def _norm_entry(entry):
    entry = entry.strip().strip('"').strip()
    while len(entry) > 3 and entry.endswith(("\\", "/")):
        entry = entry[:-1]
    return entry.replace("/", "\\").lower()


def path_has_entry(path_value, entry):
    """Whether a ``;``-separated PATH holds ``entry``, ignoring case and a
    trailing backslash."""
    want = _norm_entry(entry)
    return any(_norm_entry(part) == want for part in (path_value or "").split(";") if part.strip())


def path_with_entry(path_value, entry):
    """PATH with ``entry`` appended, or unchanged when it is already there."""
    path_value = path_value or ""
    if path_has_entry(path_value, entry):
        return path_value
    if path_value and not path_value.endswith(";"):
        path_value += ";"
    return path_value + entry


def path_without_entry(path_value, entry):
    """PATH with every copy of ``entry`` removed and everything else kept as is."""
    want = _norm_entry(entry)
    parts = (path_value or "").split(";")
    return ";".join(p for p in parts if not (p.strip() and _norm_entry(p) == want))


def windows_bin_dir(executable=None):
    """The install's bin folder, or None when this is not an installed copy."""
    folder = Path(executable or sys.executable).resolve().parent
    bin_dir = folder / "bin"
    short, long_ = command_names()
    if not (folder / "unins000.exe").is_file() or not (bin_dir / f"{long_}.cmd").is_file():
        return None
    return bin_dir


def _broadcast_environment_change():
    """Tell Explorer the environment changed, so new terminals see the PATH."""
    try:
        import ctypes
        from ctypes import wintypes
        HWND_BROADCAST, WM_SETTINGCHANGE, SMTO_ABORTIFHUNG = 0xFFFF, 0x001A, 0x0002
        result = wintypes.DWORD()
        ctypes.windll.user32.SendMessageTimeoutW(
            HWND_BROADCAST, WM_SETTINGCHANGE, 0, "Environment",
            SMTO_ABORTIFHUNG, 1000, ctypes.byref(result))
    except Exception:
        pass


def windows_add_to_path(bin_dir, winreg=None, broadcast=_broadcast_environment_change):
    """Add ``bin_dir`` to HKCU\\Environment\\Path. True when it was added."""
    if winreg is None:
        import winreg  # type: ignore[no-redef]
    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0,
                        winreg.KEY_READ | winreg.KEY_SET_VALUE) as key:
        try:
            value, kind = winreg.QueryValueEx(key, "Path")
        except FileNotFoundError:
            value, kind = "", winreg.REG_EXPAND_SZ
        if kind not in (winreg.REG_SZ, winreg.REG_EXPAND_SZ):
            return False  # not a string; leave it alone
        new = path_with_entry(value, str(bin_dir))
        if new == value:
            return False
        winreg.SetValueEx(key, "Path", 0, kind, new)
    broadcast()
    return True


def windows_ensure(settings, executable=None, winreg=None, broadcast=_broadcast_environment_change):
    """Once per app: the install's bin folder on the user's PATH."""
    if _flag(settings, ADDED_KEY):
        return False
    bin_dir = windows_bin_dir(executable)
    if bin_dir is None:
        return False
    added = windows_add_to_path(bin_dir, winreg=winreg, broadcast=broadcast)
    _set_flag(settings, ADDED_KEY)
    return added


# ---------------------------------------------------------------------- Linux

def _xdg(env, name, fallback):
    value = env.get(name, "")
    return value if os.path.isabs(value) else fallback


def linux_ensure(settings, env=None, dev=None):
    """Once per app: the short command beside an AppImage install's launcher.

    Only for the AppImage install-appimage.sh put in place (its marker beside
    it, its launcher in the bin folder). An existing file with the short name
    is left alone. True when the link was made.
    """
    if _flag(settings, ADDED_KEY):
        return False
    env = os.environ if env is None else env
    if dev is None:
        dev = is_dev_flavor()
    home = env.get("HOME", "")
    if not os.path.isabs(home):
        return False
    image = env.get("APPIMAGE", "")
    app = "PyReconstruct Dev" if dev else "PyReconstruct"
    local = "PyReconstruct-Dev.AppImage" if dev else "PyReconstruct.AppImage"
    root = os.path.join(_xdg(env, "XDG_DATA_HOME", os.path.join(home, ".local", "share")), app)
    if not image or os.path.realpath(image) != os.path.realpath(os.path.join(root, local)):
        return False
    if not os.path.isfile(os.path.join(root, APPIMAGE_MARKER)):
        return False
    bin_dir = _xdg(env, "XDG_BIN_HOME", os.path.join(home, ".local", "bin"))
    short, long_ = command_names(dev)
    launcher = os.path.join(bin_dir, long_)
    try:
        with open(launcher, encoding="utf-8", errors="replace") as f:
            if LAUNCHER_TAG not in f.read(4096):
                return False
    except OSError:
        return False
    alias = os.path.join(bin_dir, short)
    made = False
    if not os.path.lexists(alias):
        os.symlink(long_, alias)
        made = True
    _set_flag(settings, ADDED_KEY)
    return made


# ------------------------------------------------------------------- dispatch

def open_settings():
    from PySide6.QtCore import QSettings
    from PyReconstruct.modules.constants.settings_domain import domain_for
    return QSettings(*domain_for(DECLINED_KEY, ADDED_KEY))


def ensure_silent(settings=None):
    """The Windows and Linux steps, which need no prompt. Never raises."""
    if not getattr(sys, "frozen", False):
        return False
    try:
        settings = settings or open_settings()
        if sys.platform == "win32":
            return windows_ensure(settings)
        if sys.platform.startswith("linux"):
            return linux_ensure(settings)
    except Exception as e:
        log_problem(f"terminal commands: {e!r}")
    return False


def macos_pending(settings=None):
    """(bundle, fixes, settings) when the macOS links need the user's yes, else None.
    Never raises."""
    if not getattr(sys, "frozen", False) or sys.platform != "darwin":
        return None
    try:
        bundle = own_macos_bundle()
        if bundle is None:
            return None
        settings = settings or open_settings()
        fixes = macos_offer(bundle, settings)
        return (bundle, fixes, settings) if fixes else None
    except Exception as e:
        log_problem(f"terminal commands: {e!r}")
        return None


def log_problem(message):
    try:
        from PyReconstruct.modules.backend.func.logging_setup import log_note
        log_note(message)
    except Exception:
        pass
